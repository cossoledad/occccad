import assert from "node:assert/strict";
import {assemblyConflictCurrent,assemblyConflictRepairs,assemblyConflictEvidenceLabel,AssemblyConflictResponseGate} from "../assembly-conflict.ts";
const report={documentId:"p",baseRevisionId:"r1",status:"UNKNOWN"};
assert.equal(assemblyConflictCurrent(report,"p","r1"),true);
assert.equal(assemblyConflictCurrent(report,"p","r2"),false);
assert.equal(assemblyConflictCurrent({...report,status:"STALE"},"p","r1"),false);
const gate=new AssemblyConflictResponseGate();const first=gate.begin("p","r1");gate.invalidate();
assert.equal(gate.accepts(first,report),false);const current=gate.begin("p","r2");
assert.equal(gate.accepts(first,report),false);assert.equal(gate.accepts(current,{...report,baseRevisionId:"r2"}),true);
const member={constraintId:"c",repairActions:["EDIT","SUPPRESS","MEASURE","RECONNECT"]};
assert.deepEqual(assemblyConflictRepairs(member,{id:"c",kind:"FIX_TOGETHER"}),["EDIT","SUPPRESS","RECONNECT"]);
assert.deepEqual(assemblyConflictRepairs(member,{id:"c",kind:"ANGLE",angleRelation:"PARALLEL"}),["EDIT","SUPPRESS","RECONNECT"]);
assert.equal(assemblyConflictRepairs(member,{id:"c",kind:"ANGLE",angleRelation:"DIRECTED"}).includes("MEASURE"),true);
assert.deepEqual(assemblyConflictRepairs(member,{id:"other",kind:"DISTANCE"}),[]);
assert.match(assemblyConflictEvidenceLabel({kind:"REDUNDANT"}),/不要求删除/);
assert.match(assemblyConflictEvidenceLabel({kind:"CURRENT_UNSATISFIED",oracle:"UNKNOWN"}),/未证明不可行/);
assert.match(assemblyConflictEvidenceLabel({kind:"LOCALIZED_SUSPECT"}),/未证明冲突/);
assert.match(assemblyConflictEvidenceLabel({kind:"CONFLICT",evidence:"VERIFIED_IRREDUCIBLE",oracle:"UNSAT",irreducible:true}),/不是最小基数/);
assert.doesNotMatch(assemblyConflictEvidenceLabel({kind:"CONFLICT",evidence:"NUMERICAL_UNKNOWN",oracle:"UNKNOWN",irreducible:false}),/已验证不可约/);
