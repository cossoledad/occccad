import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(new URL("../../../../package.json", import.meta.url));
const { createServer } = await import(require.resolve("vite"));
const server = await createServer({ appType: "custom", logLevel: "silent", server: { middlewareMode: true } });
try {
  const { contextualToolbars, commandSection, searchCommands } = await server.ssrLoadModule("/src/features/workbench/workbench-command-model.ts");
  const { CommandRegistry } = await server.ssrLoadModule("/src/cad/command/command-registry.ts");
  const { mockToolbarCatalog } = await server.ssrLoadModule("/src/api/mock-toolbar-catalog.ts");
  const catalog = mockToolbarCatalog.toolbars;
  const registry = new CommandRegistry();
  let executions = 0;
  registry.register({ id: "part.pad", execute: () => executions++ });
  registry.register({ id: "part.pocket", isEnabled: () => false, execute: () => executions++ });
  registry.register({ id: "part.revolve", isVisible: () => false, execute: () => executions++ });
  const state = (id) => registry.state(id);
  const part = contextualToolbars([...catalog].reverse(), "PART_DESIGN");
  assert.ok(part.every((item) => item.workbench === "ALL" || item.workbench === "PART_DESIGN"));
  assert.deepEqual(part.map((item) => item.sortOrder), [...part.map((item) => item.sortOrder)].sort((a, b) => a - b));
  assert.equal(commandSection(part.find((item) => item.id === "view-navigation")), "view");
  assert.equal(commandSection(part.find((item) => item.id === "history")), "document");
  assert.deepEqual(searchCommands(part, "", state).map((item) => item.commandId), ["part.pad", "part.pocket"]);
  assert.equal(searchCommands(part, "PART.PAD 拉伸", state).length, 1);
  assert.equal(searchCommands(part, "不存在", state).length, 0);
  assert.equal(searchCommands(contextualToolbars(catalog, "SKETCHER"), "拉伸", state).length, 0);
  assert.equal(searchCommands([...part, ...part], "", state).length, 2);
  assert.equal(await registry.execute("part.pocket"), false);
  assert.equal(await registry.execute("part.revolve"), true, "entry visibility does not authorize execution");
  assert.equal(await registry.execute("unknown"), false);
  assert.equal(await registry.execute("part.pad"), true);
  assert.equal(executions, 2);
  console.log("Workbench context, discovery, execution gates passed.");
} finally { await server.close(); }
