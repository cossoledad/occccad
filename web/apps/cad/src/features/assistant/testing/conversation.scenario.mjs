import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire(new URL("../../../../package.json",import.meta.url));
const {createServer}=await import(require.resolve("vite"));
const server=await createServer({appType:"custom",logLevel:"silent",server:{middlewareMode:true}});
try{
 const {mergeMessagePage,newerRun,presentedAcknowledgment,verificationPassed,runActive}=await server.ssrLoadModule("/src/features/assistant/conversation-model.ts");
 const first={id:"a",sequence:1,requestId:"request",status:"RECEIVED"};
 const complete={...first,status:"APPLIED"};
 let state=mergeMessagePage(undefined,{items:[complete],nextAfter:1,hasMore:false});
 state=mergeMessagePage(state,{items:[first],nextAfter:1,hasMore:false});
 assert.equal(state.items[0].status,"APPLIED","late polling must not revive a received instruction");
 const next={...first,id:"b",sequence:2,requestId:"new",status:"WAITING_BOUNDARY"};
 state=mergeMessagePage(state,{items:[next],nextAfter:2,hasMore:false});
 state=mergeMessagePage(state,{items:[complete],nextAfter:1,hasMore:false});
 assert.equal(state.items.length,2,"old pages must not erase a recently accepted instruction");assert.equal(state.nextAfter,2);
 state=mergeMessagePage(state,{items:Array.from({length:35},(_,i)=>({...first,id:`other-${i}`,sequence:i+3,status:"ANSWERED"})),nextAfter:37,hasMore:false});
 assert.equal(state.items.length,30);assert.equal(state.hasEarlier,true);assert.equal(state.items[0].sequence,8,"only the visible page remains in memory; older history is server-paged");
 const run={id:"run",documentId:"part",version:6,epoch:2,goalVersion:3,status:"EXECUTING",latestRevisionId:"head",presentedRevisionId:"older",tokenBudget:null,usage:{total_tokens:2_000_000}};
 assert.equal(newerRun(run,{...run,version:5}),run);assert.equal(newerRun(run,{...run,version:7,epoch:1}),run,"late old-epoch events cannot revive cancelled planning");
 assert.equal(presentedAcknowledgment(run,{documentId:"part",revisionId:"older"}),undefined);
 assert.equal(presentedAcknowledgment(run,{documentId:"other",revisionId:"head"}),undefined);
 assert.equal(presentedAcknowledgment(run,{documentId:"part",revisionId:"head"}),"head");
 assert.equal(presentedAcknowledgment({...run,presentedRevisionId:"head"},{documentId:"part",revisionId:"head"}),undefined);
 assert.equal(verificationPassed({...run,verification:{status:"VERIFIED",revisionId:"head",goalVersion:2}}),false,"old goal checks cannot verify a modified goal");
 assert.equal(verificationPassed({...run,verification:{status:"VERIFIED",revisionId:"older",goalVersion:3}}),false);
 assert.equal(verificationPassed({...run,verification:{status:"VERIFIED",revisionId:"head",goalVersion:3}}),true);
 assert.equal(runActive(run),true,"million-token cumulative usage has no client-side termination condition");
 console.log("Durable Run ordering, bounded history pages, goal verification and exact presentation acknowledgment passed.");
}finally{await server.close()}
