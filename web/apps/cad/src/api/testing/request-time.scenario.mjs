import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
const require = createRequire(new URL("../../../package.json", import.meta.url));
const ts = require("typescript");
const source = await readFile(new URL("../../utils/performance.ts", import.meta.url), "utf8");
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const perf = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
let now = 0;
Object.defineProperty(globalThis, "performance", { value: { now: () => now } });
let notifications = 0;
const unsubscribe = perf.subscribeClientPerformance(() => notifications++);
assert.equal(perf.lastClientPerformanceSample(), undefined);
let complete;
const pending = perf.measureClientRequest("WS update", () => new Promise(resolve => { complete = resolve; }));
assert.equal(notifications, 0);
now = 43;
complete({ accepted: true });
assert.deepEqual(await pending, { accepted: true });
assert.equal(perf.lastClientPerformanceSample().durationMs, 43);
assert.equal(notifications, 1);
const failure = Object.assign(new Error("backend failure"), { status: 503 });
await assert.rejects(perf.measureClientRequest("HTTP failed", async () => { now = 70; throw failure; }), error => error === failure);
assert.equal(perf.lastClientPerformanceSample().status, 503);
assert.equal(perf.lastClientPerformanceSample().durationMs, 27);
await assert.rejects(perf.measureClientRequest("WS cancelled", async () => { now = 75; throw new DOMException("Aborted", "AbortError"); }), { name: "AbortError" });
assert.equal(perf.lastClientPerformanceSample().durationMs, 5);
// Last completed request wins even if a slower concurrent request began first.
let slow;
const first = perf.measureClientRequest("slow", () => new Promise(resolve => { slow = resolve; }));
await perf.measureClientRequest("fast", async () => { now = 80; });
assert.equal(perf.lastClientPerformanceSample().name, "fast");
now = 100; slow(); await first;
assert.equal(perf.lastClientPerformanceSample().name, "slow");
unsubscribe();
const before = notifications;
for (let i = 0; i < 210; i++) await perf.measureClientRequest("bounded", async () => undefined);
assert.equal(perf.clientPerformanceSnapshot().length, 200);
assert.equal(notifications, before);
console.log("Request wall time, failures, cancellation and subscriptions passed.");
